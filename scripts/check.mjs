import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const html=read('index.html'),client=read('app.js'),sw=read('sw.js');
const version=JSON.parse(read('version.json')).version;
assert.match(html,new RegExp('content="'+version.replaceAll('.','\\.')+'"'));
for(const ref of ['app.js?v='+version,'styles.css?v='+version])assert.ok(html.includes(ref));
assert.ok(sw.includes("const VERSION = '"+version+"'"));
assert.ok(client.includes(version));
assert.ok(html.includes('<meta name="psd-api-base" content="https://dbd-player-search.m-aa-k-one-for-all-a.chatgpt.site/api/">'));
assert.ok(html.includes("connect-src 'self' https://dbd-player-search.m-aa-k-one-for-all-a.chatgpt.site"));
for(const forbidden of ['id="open-settings"','settings-dialog','Steam BAN'])assert.ok(!html.includes(forbidden),forbidden);
for(const forbidden of ['function generateLinks','function searchQuery','site:steamcommunity.com','steamcommunity.com/search/users','PSD_ADMIN_TOKEN','sourceMappingURL'])assert.ok(!client.includes(forbidden),forbidden);
for(const id of ['history-days','history-day-dialog','history-day-list'])assert.ok(html.includes('id="'+id+'"'));
for(const id of ['history-files','save-today-history','save-history-file','history-file-title'])assert.ok(!html.includes('id="'+id+'"'));
const manifest=JSON.parse(read('manifest.webmanifest'));
const refs=[...html.matchAll(/(?:src|href)="(\.\/[^"?#]+)[^"]*"/g)].map(m=>m[1]);
refs.push(...manifest.icons.map(icon=>icon.src));
refs.push(...[...read('styles.css').matchAll(/url\(['"]?(\.\/[^)'"?#]+)/g)].map(m=>m[1]));
for(const ref of refs)assert.ok(fs.statSync(path.join(root,ref)).isFile(),ref);
for(const [file,size] of [['knight-detective-eye-180-v1.png',180],['knight-detective-eye-192-v1.png',192],['knight-detective-eye-512-v1.png',512]]){const png=fs.readFileSync(path.join(root,'icons',file));assert.equal(png.readUInt32BE(16),size);assert.equal(png.readUInt32BE(20),size);}
const handlers={},deleted=[],assets=[];
let operation;
const context=vm.createContext({URL,Request,self:{registration:{scope:'https://example.test/PlayerSearch-DBD/'},addEventListener:(name,fn)=>handlers[name]=fn,clients:{claim:async()=>{}}},caches:{keys:async()=>['foreign','psd:%2FPlayerSearch-DBD%2F:3.3.0','psd:%2FOther%2F:3.3.0'],delete:async key=>deleted.push(key),open:async()=>({addAll:async items=>assets.push(...items)})}});
vm.runInContext(sw,context);
handlers.install({waitUntil:value=>operation=value});await operation;
for(const asset of assets)assert.ok(fs.statSync(path.join(root,new URL(asset.url).pathname.replace('/PlayerSearch-DBD/',''))).isFile());
handlers.activate({waitUntil:value=>operation=value});await operation;
assert.deepEqual(deleted,['psd:%2FPlayerSearch-DBD%2F:3.3.0']);
for(const url of ['https://dbd-player-search.m-aa-k-one-for-all-a.chatgpt.site/api/routes','https://example.test/Other/'])handlers.fetch({request:{url,method:'POST',cache:'no-store'},respondWith:()=>assert.fail(url)});
console.log('OK: versions, public API, assets, icon sizes, source privacy, isolated offline cache');
